/* DJMAX Fever --> PS2: load the module image, run it, report.
 *
 * Boot sequence:
 *   1. copy the EBOOT's two PT_LOAD segments into the guest module window and
 *      zero its .bss, so guest absolute addresses (code, .rodata, .data,
 *      .cplinit) resolve exactly as on the PSP;
 *   2. register the 31 224 recompiled entries and the 208 import thunks;
 *   3. call module_start at 0x00091974;
 *   4. pump the cooperative thread scheduler until every guest thread is dead
 *      or blocked, or the instruction budget runs out;
 *   5. report and spin forever, so PCSX2 does not fall back to OSDSYS.
 *
 * Progress is printed to the EE TTY (0x1000F180) every 500 000 retired guest
 * instructions by ps2_probe.h. `psp_host_icount` is fed by PSP_I() that the
 * instrumented corpus calls before each guest instruction.
 */
