/* Generated by make_ps2_corpus.ps1: the 208 import thunks in the dispatch table. */
void ps2_imports_register(void);

/* From objcopy -I binary: the embedded EBOOT segments. */
extern const unsigned char seg0_start[];
extern const unsigned char seg0_end[];
extern const unsigned char seg1_start[];
extern const unsigned char seg1_end[];

#define SEG0_VADDR   0x00000000u
#define SEG1_VADDR   0x000E15D8u
#define SEG1_BSS     0x0045BCDCu      /* memsz - filesz of PT_LOAD 1 */

#define ENTRY_ADDR   0x00091974u

/* ---- probe state (ps2_probe.h) ---------------------------------------- */
uint64_t psp_host_icount;
uint32_t psp_host_pc;
uint64_t psp_host_limit       = 30000000ull;
uint64_t psp_host_next_report = PROBE_REPORT;

/* ---- stop ------------------------------------------------------------- */
static jmp_buf g_stop;
static volatile int g_stop_reason;     /* 1 budget */

void psp_host_budget_exceeded(void) {
    g_stop_reason = 1;
    longjmp(g_stop, 1);
}

/* Called from psp_hle_call when the HLE-call budget is exhausted. */
void psp_stop_now(void) {
    g_stop_reason = 3;
    longjmp(g_stop, 1);
}

/* Per guest instruction: one shared body, called from 182 k sites. */
static uint32_t g_exit_logged, g_loop_logged, g_exit2_logged, g_abort_logged;
void psp_host_i(uint32_t a) {
    psp_host_icount++;
    psp_host_pc = a;
    /* One-shot: who first drove the runtime into its _exit() spin? */
    if (a == 0x00099540u && !g_exit_logged) {
        g_exit_logged = 1;
        psp_printf("!! exit thunk at 0x99540: caller ra=0x%08X a0=0x%08X a1=0x%08X insn=%llu\n",
                   psp_cpu.r[PSP_REG_RA], psp_cpu.r[PSP_REG_A0],
                   psp_cpu.r[PSP_REG_A1], (unsigned long long)psp_host_icount);
    }
    if (a == 0x00092704u && !g_exit2_logged) {
        g_exit2_logged = 1;
        psp_printf("!! exit() 0x92704: caller ra=0x%08X a0=0x%08X insn=%llu\n",
                   psp_cpu.r[PSP_REG_RA], psp_cpu.r[PSP_REG_A0],
                   (unsigned long long)psp_host_icount);
        psp_printf("   last NIDs:");
        for (int k = 7; k >= 0; k--) {
            const uint32_t n = psp_hle_last_nid(k);
            if (n) psp_printf(" %X", n);
        }
        psp_printf("\n");
    }
    if (a == 0x000925B8u && !g_abort_logged) {
        g_abort_logged = 1;
        const uint32_t p = psp_cpu.r[PSP_REG_A0];
        psp_printf("!! free() sanity abort: ptr=0x%08X header=0x%08X s0=0x%08X insn=%llu\n",
                   p, p ? psp_read32(p) : 0, psp_cpu.r[PSP_REG_S0],
                   (unsigned long long)psp_host_icount);
    }
    if (a == 0x00091F44u && !g_loop_logged) {
        g_loop_logged = 1;
        psp_printf("!! exit helper 0x91F44: ra=0x%08X a0=0x%08X insn=%llu\n",
                   psp_cpu.r[PSP_REG_RA], psp_cpu.r[PSP_REG_A0],
                   (unsigned long long)psp_host_icount);
    }
    if (psp_host_icount >= psp_host_next_report) psp_probe_tick();
}

/* Called by psp_host_i every PROBE_REPORT instructions: progress + budget. */
void psp_probe_report(void);   /* printer, defined below */

void psp_probe_tick(void) {
    psp_host_next_report += PROBE_REPORT;
    psp_probe_report();
    if (psp_host_icount >= psp_host_limit) psp_host_budget_exceeded();
}

void psp_probe_report(void) {
    psp_printf("[%llu] pc=0x%08X nids=%d calls=%llu bad=%llu thr=%d/%d cur=%s\n",
               (unsigned long long)psp_host_icount, psp_host_pc,
               psp_hle_distinct(), (unsigned long long)psp_hle_total_calls(),
               (unsigned long long)psp_mem_bad_access,
               ps2_sched_live(), ps2_sched_created(), ps2_sched_current_name());
}

/* Selective guest watch: only the sites patched in build/ps2/src call this.
 * Measures the guest allocator (all mallocs) and the ExitGame branch. */
static uint32_t g_big_alloc, g_malloc_seq, g_malloc_n, g_malloc_size[96], g_malloc_res[96];
static uint32_t g_exit_branch_logged, g_exit_wrapper_logged, g_fe8_logged;
#ifdef PS2_WATCH
void psp_watch(uint32_t site) {
    switch (site) {
    case 0x00099718u:                       /* operator new(size) */
        g_malloc_seq++;
        if (g_malloc_n < 96) {
            g_malloc_n++;
            g_malloc_size[g_malloc_n - 1] = psp_cpu.r[PSP_REG_A0];
            g_malloc_res[g_malloc_n - 1] = 0xDEADBEEFu;
        }
        if (psp_cpu.r[PSP_REG_A0] >= 0x40000u) g_big_alloc = psp_cpu.r[PSP_REG_A0];
        break;
    case 0x0009F900u: {                     /* arena_alloc(arena, size) */
        const uint32_t arena = psp_cpu.r[PSP_REG_A0];
        const uint32_t size  = psp_cpu.r[PSP_REG_A1];
        if (size >= 0x40000u) {
            psp_printf("[w] arena_alloc arena=0x%08X size=%u words:", arena, size);
            for (int i = 0; i < 8; i++)
                psp_printf(" %08X", psp_read32(arena + (uint32_t)i * 4u));
            psp_printf("\n");
        }
        break;
    }
    case 0x0009F944u:                       /* after call 0xA0828 (sysmalloc) */
        if (g_big_alloc) psp_printf("[w] sysmalloc -> v0=0x%08X\n", psp_cpu.r[PSP_REG_V0]);
        break;
    case 0x00099730u:                       /* malloc returned to operator new */
        if (g_malloc_n) g_malloc_res[g_malloc_n - 1] = psp_cpu.r[PSP_REG_V0];
        if (g_big_alloc) {
            psp_printf("[w] malloc(%u) -> v0=0x%08X\n", g_big_alloc, psp_cpu.r[PSP_REG_V0]);
            g_big_alloc = 0;
        }
        break;
    case 0x00000FE8u:                       /* exit/deinit routine entry */
        if (!g_fe8_logged) {
            g_fe8_logged = 1;
            psp_printf("[w] enter 0xFE8: ra=0x%08X a0=%08X a1=%08X a2=%08X a3=%08X t0=%08X t1=%08X t2=%08X t3=%08X sp=0x%08X\n",
                       psp_cpu.r[PSP_REG_RA], psp_cpu.r[PSP_REG_A0], psp_cpu.r[PSP_REG_A1],
                       psp_cpu.r[PSP_REG_A2], psp_cpu.r[PSP_REG_A3], psp_cpu.r[PSP_REG_T0],
                       psp_cpu.r[PSP_REG_T1], psp_cpu.r[PSP_REG_T2], psp_cpu.r[PSP_REG_T3],
                       psp_cpu.r[PSP_REG_SP]);
            psp_hle_dump_ring();
        }
        break;
    case 0x0000114Cu:                       /* ExitGame error branch */
        if (!g_exit_branch_logged) {
            g_exit_branch_logged = 1;
            psp_printf("[w] exit branch 0x114C: s0=0x%08X v0=0x%08X ra=0x%08X sp=0x%08X\n",
                       psp_cpu.r[PSP_REG_S0], psp_cpu.r[PSP_REG_V0],
                       psp_cpu.r[PSP_REG_RA], psp_cpu.r[PSP_REG_SP]);
            psp_hle_dump_ring();
        }
        break;
    case 0x00001158u:                       /* sceKernelExitGame wrapper entry */
        if (!g_exit_wrapper_logged) {
            g_exit_wrapper_logged = 1;
            psp_printf("[w] ExitGame wrapper 0x1158: caller ra=0x%08X s0=0x%08X\n",
                       psp_cpu.r[PSP_REG_RA], psp_cpu.r[PSP_REG_S0]);
        }
        break;
    default: break;
    }
}
#else
void psp_watch(uint32_t site) { (void)site; }   /* instrumentation off by default */
#endif

/* Dump the malloc sequence once, at report time: size -> result, in order. */
void psp_watch_dump(void) {
    psp_printf("[malloc] %u calls recorded (%u total)\n", g_malloc_n, g_malloc_seq);
    for (uint32_t i = 0; i < g_malloc_n; i++)
        psp_printf("  #%u size=%u -> 0x%08X\n", i + 1, g_malloc_size[i], g_malloc_res[i]);
}

/* ---- dispatch miss: keep going, but say where -------------------------- */
static uint32_t g_miss_logged;
static void on_miss(uint32_t addr) {
    if (g_miss_logged < 12) {
        g_miss_logged++;
        psp_printf("!! dispatch miss 0x%08X at pc=0x%08X (insn %llu)\n",
                   addr, psp_host_pc, (unsigned long long)psp_host_icount);
    }
}

static void report(const char *why) {
    psp_printf("--- report (%s) ---\n", why);
    psp_printf("pc            : 0x%08X\n", psp_host_pc);
    psp_printf("instructions  : %llu\n", (unsigned long long)psp_host_icount);
    psp_printf("nids distinct : %d   calls: %llu (unimplemented %llu)\n",
               psp_hle_distinct(), (unsigned long long)psp_hle_total_calls(),
               (unsigned long long)psp_hle_unimplemented_calls());
    psp_printf("bad accesses  : %llu\n", (unsigned long long)psp_mem_bad_access);
    psp_printf("dispatch      : %u entries, %llu misses\n",
               psp_dispatch_count(), (unsigned long long)psp_dispatch_misses());
    psp_printf("last HLE caller: ra=0x%08X pc=0x%08X\n",
               psp_hle_last_ra(), psp_cpu.pc);
    psp_printf("threads       : %d created, %d live\n",
               ps2_sched_created(), ps2_sched_live());
    psp_printf("cplinit ctors : %u of 7\n", psp_dispatch_ctor_hits());
    psp_printf("NID calls     : GeListEnQueue=%u GeDrawSync=%u SetFrameBuf=%u IoOpen=%u\n",
               psp_hle_calls(0xAB49E76Au), psp_hle_calls(0xB287BD61u),
               psp_hle_calls(0x289D82FEu), psp_hle_calls(0x109F50BCu));
    psp_printf("low-addr calls: %u", psp_dispatch_low_calls());
    for (int i = 0; i < 8; i++) {
        const uint32_t a = psp_dispatch_low_addr(i);
        if (!a) break;
        psp_printf(" 0x%X", a);
    }
    psp_printf("\n");
    psp_printf("top NIDs:\n");
    psp_hle_dump_counts(12);
    psp_watch_dump();
    ps2_sched_dump_stacks();
}

/* A CPU exception otherwise parks the EE silently in the BIOS. Never returns. */
static void ee_exception(void) {
    uint32_t epc, cause, badv;
    __asm__ volatile("mfc0 %0, $14; mfc0 %1, $13; mfc0 %2, $8" : "=r"(epc), "=r"(cause), "=r"(badv));
    psp_printf("!! EE exception cause=%u epc=0x%08X badvaddr=0x%08X cur=%s guest pc=0x%08X ra=0x%08X sp=0x%08X\n",
               (cause >> 2) & 31u, epc, badv, ps2_sched_current_name(), psp_cpu.pc,
               psp_cpu.r[PSP_REG_RA], psp_cpu.r[PSP_REG_SP]);
    for (;;) { }
}

extern uint32_t ps2_sas_endmask(void);
extern uint32_t ps2_io_total_reads;
extern uint32_t ps2_sas_core_calls;
uint32_t g_dbg_3ecc, g_dbg_3ddc;   /* TEMP: VCE layer loop profiling */
static uint32_t g_watch_cfg, g_watch_vbl;   /* TEMP: watch armed at a vblank */

/* TEMP sampling profiler: the host PC each vblank start/end interrupt lands on (EPC),
 * dumped every 20 s as "pc:count" pairs, resolved offline against the ELF's nm.
 * ponytail: 120 samples/s; a timer interrupt would sample faster if this is too coarse. */
#define PROF_N 4096u
static uint32_t prof_pc[PROF_N], prof_ct[PROF_N], prof_total, prof_lost;

/* EPC inside the handler is the kernel's dispatcher (0x81FE0); the interrupted PC is in
 * the kernel's save area. Find it once: kernel words that point into our .text and
 * change between samples. */
#define TXT_LO 0x00100000u
#define TXT_HI 0x00570000u
#define CAND_N 2048u
static uint32_t cand_a[CAND_N], cand_v[CAND_N], cand_c[CAND_N], cand_n;
static volatile uint32_t *prof_slot;

static void prof_find(void) {
    static uint32_t calls;
    calls++;
    if (calls == 10u) {
        for (uint32_t a = 0x80000000u; a < 0x80100000u && cand_n < CAND_N; a += 4u) {
            const uint32_t v = *(volatile uint32_t *)a;
            if (v >= TXT_LO && v < TXT_HI && !(v & 3u)) { cand_a[cand_n] = a; cand_v[cand_n++] = v; }
        }
    } else if (calls > 10u && calls < 300u) {
        for (uint32_t i = 0; i < cand_n; i++) {
            const uint32_t v = *(volatile uint32_t *)cand_a[i];
            if (v != cand_v[i] && v >= TXT_LO && v < TXT_HI) cand_c[i]++;
            cand_v[i] = v;
        }
    } else if (calls == 300u) {
        uint32_t best = 0;
        for (uint32_t i = 0; i < cand_n; i++) {
            if (cand_c[i] > 50u) psp_printf("[prof] cand 0x%08X changed %u\n", cand_a[i], cand_c[i]);
            if (cand_c[i] > cand_c[best]) best = i;
        }
        psp_printf("[prof] %u candidates, using 0x%08X (%u)\n", cand_n, cand_a[best], cand_c[best]);
        if (cand_n && cand_c[best] > 100u) prof_slot = (volatile uint32_t *)cand_a[best];
    }
}

static void prof_hit(void) {
    uint32_t pc;
    /* Found by prof_find on this BIOS (it can also lock onto a slot that is not EPC). */
    if (!prof_slot) prof_slot = (volatile uint32_t *)0x80018CB0u;
    if (!prof_slot) { prof_find(); return; }
    pc = *prof_slot;
    prof_total++;
    for (uint32_t k = 0, h = (pc >> 2) * 2654435761u >> 20; k < 32u; k++, h = (h + 1u) & (PROF_N - 1u)) {
        if (prof_pc[h] == pc) { prof_ct[h]++; return; }
        if (!prof_pc[h]) { prof_pc[h] = pc; prof_ct[h] = 1; return; }
    }
    prof_lost++;
}

static void prof_dump(void) {
    char line[160];
    int len = 0, rare = 0;
    psp_printf("[prof] window total=%u lost=%u\n", prof_total, prof_lost);
    for (uint32_t i = 0; i < PROF_N; i++) {
        if (!prof_pc[i]) continue;
        if (prof_ct[i] < 2u) { rare++; continue; }
        len += snprintf(line + len, sizeof line - (size_t)len, " %X:%u", prof_pc[i], prof_ct[i]);
        if (len > 120) { psp_printf("[prof]%s\n", line); len = 0; }
    }
    if (len) psp_printf("[prof]%s\n", line);
    psp_printf("[prof] end singletons=%d\n", rare);
    memset(prof_pc, 0, sizeof prof_pc);
    memset(prof_ct, 0, sizeof prof_ct);
    prof_total = prof_lost = 0;
}

static int vblank_end_sampler(int cause) {
    (void)cause;
    prof_hit();
    ExitHandler();
    return 0;
}

/* Every 2 s, whatever the guest is doing: this is how a softlock shows its position. */
static int vblank_sampler(int cause) {
    static uint32_t n;
    (void)cause;
    prof_hit();
    if ((n + 1u) % 1200u == 0u) prof_dump();
    { extern uint32_t g_watch_len; if (g_watch_cfg && n + 1u == g_watch_vbl) g_watch_len = g_watch_cfg; }
    if ((++n % 120u) == 0u) {
        psp_printf("[vs] n=%u cur=%s pc=0x%08X ra=0x%08X sp=0x%08X v0=0x%08X calls=%llu frames=%u\n",
                   n, ps2_sched_current_name(), psp_cpu.pc, psp_cpu.r[PSP_REG_RA], psp_cpu.r[PSP_REG_SP],
                   psp_cpu.r[PSP_REG_V0], (unsigned long long)psp_hle_total_calls(), ps2_ge_frames_drawn());
        ps2_sched_dump_states();
        /* Song-select wait: fade (0xDDEF0), BGM status/command bytes, voices sounding. */
        psp_printf("[sel] fade=%d bgm133=%u bgm134=%u endmask=0x%08X reads=%u sascore=%u layers=%u calls3ddc=%u\n",
                   (int32_t)psp_read32(0x000DDEF0u), psp_read8(0x0053DF58u + 133u), psp_read8(0x0053DF58u + 134u),
                   ps2_sas_endmask(), ps2_io_total_reads, ps2_sas_core_calls, g_dbg_3ecc, g_dbg_3ddc);
    }
    ExitHandler();
    return 0;
}

int main(void) {
    psp_mem_init();
    {   /* TEMP: host:gewatch.txt = "<hex addr> <hex len>" arms the guest write watch */
        extern uint32_t g_watch_lo, g_watch_len;
        static char t[64];
        const int fd = open("host:gewatch.txt", O_RDONLY);
        if (fd >= 0) {
            const int n = (int)read(fd, t, sizeof t - 1);
            close(fd);
            if (n > 0) { char *e; t[n] = 0; g_watch_lo = (uint32_t)strtoul(t, &e, 16); g_watch_cfg = (uint32_t)strtoul(e, &e, 16); g_watch_vbl = (uint32_t)strtoul(e, NULL, 10); }
            psp_printf("[watch] 0x%08X +0x%X from vblank %u\n", g_watch_lo, g_watch_cfg, g_watch_vbl);
        }
    }

    const uint32_t seg0_len = (uint32_t)(seg0_end - seg0_start);
    const uint32_t seg1_len = (uint32_t)(seg1_end - seg1_start);

    psp_printf("\n=== DJMAX Fever / PS2: module image + scheduler ===\n");
    psp_printf("seg0 %u B @0x%08X, seg1 %u B @0x%08X, bss %u B\n",
               seg0_len, SEG0_VADDR, seg1_len, SEG1_VADDR, SEG1_BSS);
    psp_printf("before load : [0x0]=0x%08X [0x%08X]=0x%08X\n",
               psp_read32(0), SEG1_VADDR, psp_read32(SEG1_VADDR));

    if (psp_mem_load_module(seg0_start, seg0_len,
                            seg1_start, seg1_len,
                            SEG1_VADDR, SEG1_BSS) != 0) {
        psp_printf("FATAL: segment copy failed\n");
    }
    psp_printf("after load  : [0x0]=0x%08X [0x%08X]=0x%08X\n",
               psp_read32(0), SEG1_VADDR, psp_read32(SEG1_VADDR));

    psp_cpu_reset();
    psp_recomp_register();
    ps2_imports_register();
    psp_printf("dispatch    : %u entries (corpus + import thunks)\n",
               psp_dispatch_count());

    ps2_sysmem_init();
    ps2_sched_init();
    psp_hle_init();
    ps2_audio_install();
    { extern void ps2_mpeg_install(void); ps2_mpeg_install(); }   /* after: its NIDs win */
    { extern void ps2_savedata_install(void); ps2_savedata_install(); }
    ps2_ge_init();
    ps2_pad_init();
    { extern void ps2_at3_init(void *, uint32_t);       /* seg0 is dead once copied */
      ps2_at3_init((void *)seg0_start, (uint32_t)(seg0_end - seg0_start)); }
    ps2_snd_init();
    { extern void ps2_savedata_init(void); ps2_savedata_init(); }   /* memory card modules */
    { extern void ps2_songs_init(void); ps2_songs_init(); }         /* records of the extra songs */
    { extern void ps2_at3_selftest(void); ps2_at3_selftest(); }   /* only with host:at3test.txt */

    psp_set_miss_handler(on_miss);
    AddIntcHandler(2, vblank_sampler, 0);
    EnableIntc(2);
    AddIntcHandler(3, vblank_end_sampler, 0);
    EnableIntc(3);
    for (int c = 1; c <= 3; c++) SetVTLBRefillHandler(c, ee_exception);
    for (int c = 4; c <= 13; c++) if (c != 8) SetVCommonHandler(c, ee_exception);

    psp_cpu.r[PSP_REG_SP] = PSP_RAM_BASE + PSP_RAM_SIZE - 0x100u;
    psp_cpu.r[PSP_REG_GP] = 0;              /* module info says gp = 0 */
    psp_cpu.r[PSP_REG_A0] = 0;
    psp_cpu.r[PSP_REG_A1] = 0;
    psp_cpu.r[PSP_REG_RA] = 0;

    psp_printf("entry       : 0x%08X, limit %llu instructions\n",
               ENTRY_ADDR, (unsigned long long)psp_host_limit);

    if (setjmp(g_stop) == 0) {
        psp_call_from_host(ENTRY_ADDR);
        psp_printf("module_start returned v0=0x%08X after %llu insns\n",
                   psp_cpu.r[PSP_REG_V0], (unsigned long long)psp_host_icount);
        psp_printf("threads created=%d live=%d ready=%d\n",
                   ps2_sched_created(), ps2_sched_live(), ps2_sched_ready());
        const int sw = ps2_sched_pump();
        psp_printf("scheduler drained after %d switches, %llu insns\n",
                   sw, (unsigned long long)psp_host_icount);
        report("threads blocked or dead");
    } else {
        report(g_stop_reason == 1 ? "instruction budget" :
               g_stop_reason == 3 ? "HLE call budget" : "stopped");
    }

    psp_printf("=== staying alive (no reset to OSDSYS) ===\n");
    for (;;) {
        __asm__ volatile("nop");
    }
    return 0;
}
