# make_ps2_corpus.ps1 -- prepare the corpus the EE build compiles.
#
# Reuses the host generator (port/tools/make_corpus.ps1) for the two things that
# must not be re-implemented:
#   - one PSP_I(0xADDR) before every emitted guest instruction (instruction
#     count + PC), force-included as port/ps2/ps2_probe.h;
#   - the declared loader fixup for psp_body_00092E28 (r_s0 = 0x000E15D8u), so
#     the .cplinit table is walked and the C++ constructors run.
#
# Then it replaces the host import shim with a PS2 one: the same 208
# psp_import_<stub> entry points, each calling psp_hle_call(NID), plus
# ps2_imports_register() which puts every thunk in the dispatch table (an
# indirect call through a function pointer to a stub must land on the thunk, not
# on the emitted empty body).
param(
    [string]$EmitDir = "D:\DJMX\build\emit",
    [string]$OutDir  = "",
    [switch]$BaseOnly
)

$ErrorActionPreference = "Stop"

# Relocate the EBOOT once, then emit from it: the embedded segments (build.sh) and
# the emitted code then agree on every address. The toolkit's own P8 fixup sees all
# addends >= seg1 and does nothing, so "P8: 0 of N" is the expected output.
$root = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path.Replace('\','/')
if (-not $PSBoundParameters.ContainsKey('EmitDir')) { $EmitDir = "$root/build/emit" }
if (-not $OutDir) { $OutDir = if ($BaseOnly) { "$root/build/ps2/src-base" } else { "$root/build/ps2/src" } }
New-Item -ItemType Directory -Force -Path "$root/build",$EmitDir | Out-Null
$reloc = "$root/build/eboot_reloc.bin"
& python "$root/tools-src/reloc_eboot.py" "$root/.game/DUMPED EBOOT/ULUS10403_EBOOT.BIN" $reloc
if ($LASTEXITCODE -ne 0) { throw "reloc_eboot failed" }
Get-ChildItem $EmitDir -Filter "djmax_funcs_*.c" | Remove-Item -Force   # unit count can shrink
& "$root/.tools/psprecomp/build/tools/allegrexrecomp/Release/allegrexrecomp.exe" emit $reloc $EmitDir djmax
if ($LASTEXITCODE -ne 0) { throw "emit failed" }

# Start clean: the emit file set can change between regenerations, and a stale
# djmax_funcs_NNN.c would be linked as if it were current.
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
Get-ChildItem $OutDir -Filter "djmax_funcs_*.c" | Remove-Item -Force
foreach ($f in @("djmax_funcs.h","djmax_register.c","ps2_imports.c","djmax_imports_host.c")) {
    $p = Join-Path $OutDir $f
    if (Test-Path $p) { Remove-Item $p -Force }
}

& (Join-Path $PSScriptRoot "..\tools\make_corpus.ps1") -EmitDir $EmitDir -OutDir $OutDir

# Native replacements (port/ps2/ps2_libc.c): drop the emitted wrapper of each, so the
# native function of the same name is the one every call site and the dispatch table get.
$native = @("0009A18C", "0009A260", "0009A390", "00079A58", "00079EE8", "00079C1C")   # libc: ps2_libc.c, zlib: ps2_zlib.c
foreach ($f in Get-ChildItem $OutDir -Filter "djmax_funcs_*.c") {
    $t = [System.IO.File]::ReadAllText($f.FullName)
    $orig = $t
    foreach ($a in $native) {
        $t = $t.Replace("void psp_func_$a(void) { psp_body_$a(0x${a}u); }", "/* psp_func_${a}: native (ps2_libc.c / ps2_zlib.c) */")
    }
    if ($t -ne $orig) { [System.IO.File]::WriteAllText($f.FullName, $t, (New-Object System.Text.UTF8Encoding($false))) }
}

# Calls whose delay slot another function owns go out without it (tools-src/fix_foreign_slots.py).
& python "$root/tools-src/fix_foreign_slots.py" $OutDir
if ($LASTEXITCODE -ne 0) { throw "fix_foreign_slots failed" }

# lwr/lwl and swr/swl pairs -> one unaligned psp_read32/psp_write32 (tools-src/fuse_unaligned.py).
& python "$root/tools-src/fuse_unaligned.py" $OutDir
if ($LASTEXITCODE -ne 0) { throw "fuse_unaligned failed" }

# More than 60 songs: the song table, list entries and records unpinned (tools-src/patch_songs.py, port/ps2/ps2_songs.c).
if (-not $BaseOnly) {
    & python "$root/tools-src/patch_songs.py" $OutDir
    if ($LASTEXITCODE -ne 0) { throw "patch_songs failed" }
}

$hostImports = Join-Path $OutDir "djmax_imports_host.c"
if (Test-Path $hostImports) { Remove-Item $hostImports -Force }

# --- PS2 import thunks -----------------------------------------------------
$src = [System.IO.File]::ReadAllText((Join-Path $EmitDir "djmax_imports.c"))
$rx  = [regex]'/\* ([^ ]+) :: NID 0x([0-9A-Fa-f]{8}) \*/\s*\r?\nvoid psp_import_([0-9A-F]{8})\(void\)'

$sb    = New-Object System.Text.StringBuilder
$regs  = New-Object System.Text.StringBuilder
$count = 0
[void]$sb.AppendLine("/* Generated by port/ps2/make_ps2_corpus.ps1 from build/emit/djmax_imports.c. */")
[void]$sb.AppendLine('#include "djmax_funcs.h"')
[void]$sb.AppendLine('#include "runtime_min.h"')
[void]$sb.AppendLine("")
foreach ($m in $rx.Matches($src)) {
    $nid = $m.Groups[2].Value.ToUpper()
    $adr = $m.Groups[3].Value.ToUpper()
    [void]$sb.AppendLine("void psp_import_$adr(void) { psp_hle_call(0x${nid}u); }")
    [void]$regs.AppendLine("    psp_register(0x${adr}u, psp_import_$adr);")
    $count++
}
if ($count -ne 208) { throw "expected 208 import thunks, rewrote $count" }
[void]$sb.AppendLine("")
[void]$sb.AppendLine("void ps2_imports_register(void) {")
[void]$sb.Append($regs.ToString())
[void]$sb.AppendLine("}")
[System.IO.File]::WriteAllText((Join-Path $OutDir "ps2_imports.c"), $sb.ToString(),
                               (New-Object System.Text.UTF8Encoding($false)))

Write-Output ("ps2 corpus: {0} import thunks" -f $count)
