# make_corpus.ps1 -- build the host-side copy of the recompiler output.
#
# The toolkit is never modified. This script takes the files `allegrexrecomp
# emit` wrote and produces D:\DJMX\build\host\src, in two steps:
#
#   1. Every emitted guest instruction gets one `PSP_I(0xADDR);` in front of its
#      C translation. That is the only honest way to count instructions and to
#      know the PC that was reached: the recompiled C runs whole functions, and
#      the runtime has no per-instruction hook (`psp_cpu.pc` is only meaningful
#      at dispatch boundaries, and dispatch does not even set it).
#      The insertion point is mechanically safe: the emitter emits each guest
#      instruction as a one-line comment followed by its C statement(s), and a
#      statement is what we insert.
#
#   2. `djmax_imports.c` is replaced by `djmax_imports_host.c`, which defines the
#      same 208 `psp_import_<stub>` entry points but routes them through
#      `psp_host_import(stub, nid, lib)` so the host can log/count per NID.
#      It also defines `psp_host_register_imports()`, which registers each import
#      thunk in the dispatch table at its stub address -- without that, an
#      indirect call through a function pointer to a stub lands on the emitted
#      `jr $ra` body, which returns without ever calling the firmware.

param(
    [string]$EmitDir = "D:\DJMX\build\emit",
    [string]$OutDir  = "D:\DJMX\build\host\src"
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $EmitDir)) { throw "emit dir not found: $EmitDir" }
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

# --- 1. instrument the function units --------------------------------------
# A plain regex replacement template: group 2 is the guest address, so it can be
# reused verbatim in the inserted statement. No scriptblock delegate, so this
# works on Windows PowerShell 5.1 as well as 7.
$rx  = [regex]'(?m)^([ \t]*)/\* ([0-9A-F]{8})  (.*)$'
$rep = '$1/* $2  $3' + "`n" + '$1PSP_I(0x$2u);'
$ins = 0
$files = Get-ChildItem -Path $EmitDir -Filter "djmax_funcs_*.c"
foreach ($f in $files) {
    $txt = [System.IO.File]::ReadAllText($f.FullName)
    $ins += $rx.Matches($txt).Count
    $out = $rx.Replace($txt, $rep)
    [System.IO.File]::WriteAllText((Join-Path $OutDir $f.Name), $out, (New-Object System.Text.UTF8Encoding($false)))
}
foreach ($f in @("djmax_funcs.h", "djmax_register.c")) {
    Copy-Item (Join-Path $EmitDir $f) (Join-Path $OutDir $f) -Force
}

# --- 1b. loader fixups -----------------------------------------------------
# A PRX's code carries relocation slots that the *PSP loader* fills in when it
# maps the module. With a static recompiler the instruction is a C literal, so
# the equivalent of that loader step is to substitute the value here -- NOT to
# edit the game. This table is declarative and reproducible: nothing in
# build/host/src is ever edited by hand, and re-running this script rebuilds the
# same corpus from build/emit plus these entries.
#
# Entry 1: the pre-init table walker. The image links `lui $s0,0 / addiu
# $s0,$s0,0` (both immediates 0, HI16+LO16 pair at 0x92E30/0x92E34, sym 0x100 =
# segment 1, addend 0), which resolves to the start of segment 1 = .cplinit at
# 0x000E15D8. With 0 it walks address 0 (the module's own code) as a table and
# no C++ constructor ever runs: measured, that costs 12.7 M invalid accesses and
# leaves every global unconstructed. With 0x000E15D8 the seven constructors run
# and the run reaches PC 0x000AA1C8 with 10 invalid accesses.
#
# P8 is the real fix: emit.c should resolve the pair from the relocation table
# itself. Until then this is the operational mitigation.
$fixups = @(
)
# --- 2. rewrite the import thunks ------------------------------------------
$src = [System.IO.File]::ReadAllText((Join-Path $EmitDir "djmax_imports.c"))
$thunk = [regex]'/\* ([^ ]+) :: NID 0x([0-9A-Fa-f]{8}) \*/\s*\r?\nvoid psp_import_([0-9A-F]{8})\(void\) \{[^}]*\}'
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by port/tools/make_corpus.ps1 from djmax_imports.c. */")
[void]$sb.AppendLine("/* Host-side import shim: same 208 entry points, routed through a logger. */")
[void]$sb.AppendLine('#include "djmax_funcs.h"')
[void]$sb.AppendLine("#include <psprecomp/dispatch.h>")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("void psp_host_import(uint32_t stub, uint32_t nid, const char *lib);")
[void]$sb.AppendLine("void psp_host_import_declare(uint32_t stub, uint32_t nid, const char *lib);")
[void]$sb.AppendLine("")
$n = 0
$regs = New-Object System.Text.StringBuilder
$decl = New-Object System.Text.StringBuilder
foreach ($m in $thunk.Matches($src)) {
    $lib = $m.Groups[1].Value
    $nid = $m.Groups[2].Value.ToUpper()
    $adr = $m.Groups[3].Value.ToUpper()
    [void]$sb.AppendLine("void psp_import_$adr(void) { psp_host_import(0x${adr}u, 0x${nid}u, ""$lib""); }")
    [void]$regs.AppendLine("    psp_register(0x${adr}u, psp_import_$adr);")
    [void]$decl.AppendLine("    psp_host_import_declare(0x${adr}u, 0x${nid}u, ""$lib"");")
    $n++
}
[void]$sb.AppendLine("")
[void]$sb.AppendLine("void psp_host_register_imports(void) {")
[void]$sb.Append($regs.ToString())
[void]$sb.AppendLine("}")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* Every import the module declares, recorded before anything runs, so the")
[void]$sb.AppendLine(" * report can say how many of the 208 have an HLE handler at all. */")
[void]$sb.AppendLine("void psp_host_declare_imports(void) {")
[void]$sb.Append($decl.ToString())
[void]$sb.AppendLine("}")
[System.IO.File]::WriteAllText((Join-Path $OutDir "djmax_imports_host.c"), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

# --- 1c. apply the loader fixups -------------------------------------------
foreach ($fx in $fixups) {
    $hit = Select-String -Path (Join-Path $OutDir "djmax_funcs_*.c") -Pattern ("static void " + $fx.func + "\(")
    if (-not $hit) { throw ("fixup target not found: " + $fx.func) }
    $path = $hit[0].Path
    $txt  = [System.IO.File]::ReadAllText($path)
    $i    = $txt.IndexOf("static void " + $fx.func + "(")
    $j    = $txt.IndexOf($fx.from, $i)
    if ($j -lt 0) { throw ("fixup pattern not found in " + $fx.func + ": " + $fx.from) }
    $txt = $txt.Substring(0, $j) + $fx.to + $txt.Substring($j + $fx.from.Length)
    [System.IO.File]::WriteAllText($path, $txt, (New-Object System.Text.UTF8Encoding($false)))
    Write-Output ("loader fixup: " + $fx.func + " -> " + $fx.to)
}
# --- report ----------------------------------------------------------------
$bytes = 0
foreach ($f in Get-ChildItem $OutDir) { $bytes += $f.Length }
Write-Output ("corpus: {0} files, {1:N0} bytes ({2:N2} MB)" -f (Get-ChildItem $OutDir).Count, $bytes, ($bytes/1MB))
Write-Output ("instrumented instruction sites: {0:N0}" -f $ins)
Write-Output ("import thunks rewritten: {0}" -f $n)
if ($n -ne 208) { throw "expected 208 import thunks, rewrote $n" }
